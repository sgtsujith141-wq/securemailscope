def test_the_upload_limit_is_enforced_while_streaming(tmp_path: Path) -> None:
    """Abandoned mid-write, not measured after the whole file lands on disk."""
    storage = CaptureStorage(tmp_path / "s", max_bytes=1024)
    import io

    payload = b"\xd4\xc3\xb2\xa1" + b"x" * 8192
    with pytest.raises(UploadRejected, match="exceeds the configured limit"):
        storage.store(io.BytesIO(payload), "big.pcap")
    assert list((tmp_path / "s" / "captures").glob("*.bin")) == [], (
        "the partial file must be removed, not left behind"
    )


