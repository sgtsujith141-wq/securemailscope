def test_all_three_formats_agree_on_the_facts(client: TestClient, analysed) -> None:
    """§20 report parity, checked field by field."""
    import io

    from pypdf import PdfReader

    identifier = analysed["investigation"]["investigation_id"]
    document = client.get(f"/api/investigations/{identifier}/export/json").json()
    html = client.get(f"/api/investigations/{identifier}/export/html").text
    pdf = PdfReader(io.BytesIO(client.get(f"/api/investigations/{identifier}/export/pdf").content))
    pdf_text = "\n".join(page.extract_text() for page in pdf.pages)
    # Long identifiers wrap across lines in the PDF, which is correct: wrapping
    # is what stops them being clipped. Comparison is therefore on text with
    # whitespace removed.
    pdf_flat = "".join(pdf_text.split())
    html_flat = "".join(html.split())

    # Capture ids
    for capture in document["captures"]:
        assert capture["capture_id"] in html_flat
        assert capture["capture_id"] in pdf_flat

    # Session count
    assert len(document["sessions"]) == 2
    for session in document["sessions"]:
        assert session["session_id"] in html_flat
        assert session["session_id"] in pdf_flat

    # Finding ids, severities and rule ids
    for finding in document["findings"]:
        assert finding["rule_id"] in html_flat
        assert finding["rule_id"] in pdf_flat
        assert finding["severity"] in html_flat

    # Policy version, score and coverage
    posture = document["posture"]
    assert document["policy_version"] in html_flat
    assert document["policy_version"] in pdf_flat
    if posture["score"] is not None:
        assert str(posture["score"]) in html_flat
        assert f"{posture['score']}/100" in pdf_flat

    # Remediation ids
    for remediation in document["remediations"]:
        assert remediation["remediation_id"] in html_flat
        assert remediation["remediation_id"] in pdf_flat

    # Blast-radius counts
    for radius in document["blast_radius"]:
        assert radius["subject"] in html_flat
        assert radius["subject"] in pdf_flat

    # ML validation status
    assert document["ml"]["classification_validation_status"] in html_flat
    assert document["ml"]["classification_validation_status"] in pdf_flat
    assert document["ml"]["anomaly_algorithm"] in html_flat
    assert document["ml"]["anomaly_algorithm"] in pdf_flat


def test_the_pdf_renders_correctly(client: TestClient, analysed, tmp_path: Path) -> None:
    """§19: not merely produced — rendered and inspected."""
    import io

    import numpy as np
    import pypdfium2 as pdfium
    from pypdf import PdfReader

    identifier = analysed["investigation"]["investigation_id"]
    data = client.get(f"/api/investigations/{identifier}/export/pdf").content
    path = tmp_path / "report.pdf"
    path.write_bytes(data)

    reader = PdfReader(io.BytesIO(data))
    assert len(reader.pages) >= 2
    # A4 at 72dpi is 595 x 842 points.
    box = reader.pages[0].mediabox
    assert abs(float(box.width) - 595) < 2
    assert abs(float(box.height) - 842) < 2

    text = "\n".join(page.extract_text() for page in reader.pages)
    assert "Executive summary" in text
    assert "Security findings" in text
    assert "Limitations" in text
    assert "Page 1" in text
    assert "Observed within analyzed captures only" in text

    document = pdfium.PdfDocument(path)
    assert len(document) == len(reader.pages)
    for index, page in enumerate(document):
        image = page.render(scale=2).to_pil().convert("L")
        array = np.asarray(image)
        ink = (array < 200).mean()
        assert ink > 0.002, f"page {index + 1} is blank"
        # Nothing may bleed into the margins: that is what clipping looks like.
        assert (array[:, -28:] < 200).mean() < 0.0005, f"page {index + 1} clips on the right"
        assert (array[:24, :] < 200).mean() < 0.0005, f"page {index + 1} clips at the top"


def test_long_values_wrap_rather_than_clipping(client: TestClient, analysed) -> None:
    """A capture id is 71 characters and must not be truncated silently."""
    import io

    from pypdf import PdfReader

    identifier = analysed["investigation"]["investigation_id"]
    data = client.get(f"/api/investigations/{identifier}/export/pdf").content
    text = "\n".join(page.extract_text() for page in PdfReader(io.BytesIO(data)).pages)
    normalised = text.replace("\n", "").replace(" ", "")
    document = client.get(f"/api/investigations/{identifier}/export/json").json()
    for capture in document["captures"]:
        assert capture["capture_id"].replace(" ", "") in normalised, (
            "a full capture identifier was clipped in the PDF"
        )
