def test_a_failed_capture_stays_visible(client: TestClient, state: AppState) -> None:
    """A partial batch failure must not vanish from the aggregate."""
    good = upload(client, "aa_tls10_static_rsa.pcap")["capture_id"]
    # A stored capture whose bytes are later truncated: it passed upload
    # validation but cannot be analysed.
    with state.database.session() as session:
        good_path = present(
            session.get(CaptureRow, good), "the stored capture row"
        ).stored_path
    broken_path = Path(good_path).parent / "deadbeef00000000000000000000beef.bin"
    broken_path.write_bytes(b"\xd4\xc3\xb2\xa1truncated")
    with state.database.session() as session:
        session.add(CaptureRow(
            capture_id="sha256:broken", storage_id="deadbeef00000000000000000000beef",
            original_name="broken.pcap", stored_path=str(broken_path),
            file_size_bytes=13, sha256="sha256:broken", file_format="PCAP",
        ))
    detail = analyse(client, state, [good, "sha256:broken"])
    names = {c["original_name"] for c in detail["captures"]}
    assert "broken.pcap" in names, "the failed capture disappeared from the inventory"


