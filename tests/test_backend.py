def test_results_survive_a_restart(tmp_path: Path) -> None:
    root = tmp_path / "app"
    first = AppState(root)
    with TestClient(create_app(first), base_url="http://127.0.0.1") as client:
        client.headers.update({TOKEN_HEADER: first.token.value})
        capture = upload(client, "aa_tls10_static_rsa.pcap")
        detail = analyse(client, first, [capture["capture_id"]])
        identifier = detail["investigation"]["investigation_id"]
    first.shutdown()

    # A fresh process over the same directory.
    second = AppState(root)
    try:
        with TestClient(create_app(second), base_url="http://127.0.0.1") as client:
            client.headers.update({TOKEN_HEADER: second.token.value})
            reloaded = client.get(f"/api/investigations/{identifier}").json()
            assert reloaded["investigation"]["finding_count"] == 4
            assert reloaded["investigation"]["posture_score"] == 59
            sessions = client.get(f"/api/investigations/{identifier}/sessions").json()
            assert sessions["total"] == 1
    finally:
        second.shutdown()


def test_an_interrupted_job_is_never_reported_as_completed(tmp_path: Path) -> None:
    database = Database(tmp_path / "db.sqlite3")
    from securemailscope.backend.database import InvestigationRow

    with database.session() as session:
        session.add(InvestigationRow(investigation_id="inv-x", name="x", status="RUNNING"))
        session.add(JobRow(job_id="job-x", investigation_id="inv-x", status="RUNNING"))
    database.close()

    recovered = Database(tmp_path / "db.sqlite3")
    assert recovered.recover_interrupted_jobs() == 1
    with recovered.session() as session:
        job = present(session.get(JobRow, "job-x"), "job-x")
        assert job.status == "FAILED"
        assert "restarted" in (job.error or "")
        assert present(
            session.get(InvestigationRow, "inv-x"), "inv-x"
        ).status == "FAILED"
    recovered.close()


